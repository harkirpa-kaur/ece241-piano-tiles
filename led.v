module third_counter (CLOCK_50, reset, start_game, t);
    input CLOCK_50;
    input reset;
	 input start_game;
    reg [24:0] little = 25'd0;
    output reg t = 1'b0;
    
    always @ (posedge CLOCK_50)
    begin
        if (!reset)
            begin
                little <= 25'd0;
                t <= 1'b0;
            end
        else if (little == 25'd25000000)
            begin
                little <= 25'd0;
                t <= 1'b1;
            end
        else if (start_game)
            begin
                t <= 1'b0;
                little <= little + 1;
            end
    end
    
endmodule

